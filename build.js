// Generates docs/index.html, a gallery of cards (title, description, screenshot, live link), one per demo.
// Screenshots live in docs/screenshots/ and are retaken only when a demo's source changes.
// npm ci && npx playwright install chromium && npm run build
// npm run build -- --no-screenshots   only rewrites docs/index.html

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const cheerio = require('cheerio');
const { chromium } = require('playwright');
const { serve } = require('./static-server');

const root = path.join(__dirname, 'docs');
const shots = path.join(root, 'screenshots');
const hashesFile = path.join(shots, 'hashes.json');

const exclusions = [
    'index.html',
    'extra.js',
    'jquery-rewire-fragment.html',
    'js_playground.js',
    'oracle.js',
    'node-server.js'
];

function escape(s) {
    return s.replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
}

function readDemos() {
    return fs.readdirSync(root).filter(file => /\.(html|js)$/.test(file) && !exclusions.includes(file)).map(file => {
        const source = fs.readFileSync(path.join(root, file));
        let title, description;
        if (file.endsWith('.html')) {
            const $ = cheerio.load(source);
            title = $('head title').text().trim();
            description = $('#description').text().trim() || $('meta[name=description]').attr('content') || '';
        } else {
            title = file;
            description = source.toString().split(/\n/)[0].replace(/^\/\/\s*/, '');
        }
        const hash = crypto.createHash('sha256').update(source).digest('hex');
        const shot = `screenshots/${file.replace(/\.[^.]+$/, '')}.jpg`;
        return { file, title, description: description.replace(/\s+/g, ' '), hash, shot };
    });
}

async function takeScreenshots(demos) {
    const hashes = fs.existsSync(hashesFile) ? JSON.parse(fs.readFileSync(hashesFile)) : {};
    const stale = demos.filter(d => hashes[d.file] !== d.hash || !fs.existsSync(path.join(root, d.shot)));
    for (const file of Object.keys(hashes)) {
        if (!demos.some(d => d.file === file)) delete hashes[file];
    }
    if (stale.length) {
        fs.mkdirSync(shots, { recursive: true });
        const { server, base } = await serve(root);
        const browser = await chromium.launch();
        try {
            for (const demo of stale) {
                const tab = await browser.newPage({ viewport: { width: 800, height: 500 } });
                try {
                    await tab.goto(base + demo.file, { waitUntil: 'load', timeout: 15000 });
                    await tab.waitForTimeout(1000);
                    await tab.screenshot({ path: path.join(root, demo.shot), type: 'jpeg', quality: 70 });
                    hashes[demo.file] = demo.hash;
                    console.log(`screenshot ${demo.shot}`);
                } catch (err) {
                    console.warn(`no screenshot for ${demo.file}: ${err.message}`);
                } finally {
                    await tab.close();
                }
            }
        } finally {
            await browser.close();
            server.close();
        }
    }
    fs.writeFileSync(hashesFile, JSON.stringify(hashes, null, 2) + '\n');
}

function card(demo) {
    const href = escape(demo.file);
    const img = fs.existsSync(path.join(root, demo.shot))
        ? `<img src="${escape(demo.shot)}" alt="Screenshot of ${escape(demo.title)}" loading="lazy" width="800" height="500">`
        : '';
    return `        <article class="card">
            <a class="shot" href="${href}">${img}</a>
            <h2><a href="${href}">${escape(demo.title)}</a></h2>
            <p>${escape(demo.description)}</p>
            <a class="live" href="${href}">Live version</a>
        </article>`;
}

function page(demos) {
    return `<!DOCTYPE html>
<!-- Generated by build.js: edit the demos, not this file. -->
<html lang="en">
<head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>Igor Rosenberg's JS demos</title>
    <meta name="description" content="Experiments in JS, to be seen as sandbox futilities.">
    <style>
        :root { color-scheme: light dark; --bg: #f6f7f9; --card: #fff; --text: #1d2125; --muted: #5c6670; --link: #0b5cad; --border: #dde1e6; }
        @media (prefers-color-scheme: dark) {
            :root { --bg: #15181c; --card: #1f2329; --text: #e6e8eb; --muted: #a0a8b2; --link: #6cb2ff; --border: #343a42; }
        }
        body { margin: 0; background: var(--bg); color: var(--text); font: 16px/1.5 system-ui, sans-serif; }
        header, main { max-width: 1100px; margin: 0 auto; padding: 0 16px; }
        header { padding-top: 32px; }
        header h1 { margin: 0 0 4px; }
        header p { margin: 0; color: var(--muted); }
        a { color: var(--link); }
        main { display: grid; grid-template-columns: repeat(auto-fill, minmax(260px, 1fr)); gap: 20px; padding-top: 24px; padding-bottom: 40px; }
        .card { display: flex; flex-direction: column; background: var(--card); border: 1px solid var(--border); border-radius: 8px; overflow: hidden; }
        .shot { display: block; aspect-ratio: 16 / 10; background: var(--border); border-bottom: 1px solid var(--border); }
        .shot img { display: block; width: 100%; height: 100%; object-fit: cover; object-position: top left; }
        .card h2 { font-size: 1.1rem; margin: 12px 14px 4px; }
        .card h2 a { color: inherit; text-decoration: none; }
        .card p { margin: 0 14px 12px; color: var(--muted); flex: 1; overflow-wrap: anywhere; }
        .live { margin: 0 14px 14px; font-weight: 600; }
    </style>
</head>
<body>
<header>
    <h1>Igor Rosenberg's JS demos</h1>
    <p>Experiments in JS, to be seen as sandbox futilities. Source on <a href="https://github.com/igorrosenberg/js_playground">GitHub</a>.</p>
</header>
<main>
${demos.map(card).join('\n')}
</main>
</body>
</html>
`;
}

async function main() {
    const demos = readDemos();
    if (!process.argv.includes('--no-screenshots')) await takeScreenshots(demos);
    fs.writeFileSync(path.join(root, 'index.html'), page(demos));
    console.log(`docs/index.html: ${demos.length} demos`);
}

main().catch(err => {
    console.error(err);
    process.exit(1);
});
